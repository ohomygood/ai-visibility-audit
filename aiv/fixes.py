def write_fixpack(res: dict, profile, out_dir: Path, provider: Provider, meter: CostMeter) -> dict:
    p = _p(profile)
    fp = Path(out_dir) / "fixpack"
    (fp / "jsonld").mkdir(parents=True, exist_ok=True)
    (fp / "shopify").mkdir(exist_ok=True)
    (fp / "content").mkdir(exist_ok=True)
    files = {}

    def w(rel, text):
        (fp / rel).write_text(text, encoding="utf-8")
        files[rel] = len(text.encode())

    w("robots.txt.snippet", robots_snippet(res))
    w("shopify/robots.txt.liquid", shopify_robots_liquid(res))
    w("jsonld/organization.jsonld", json.dumps(organization_jsonld(p), ensure_ascii=False, indent=2))
    for prod in p.get("products", [])[:10]:
        handle = prod.get("handle") or re.sub(r"\W+", "-", prod["url"])[-40:]
        w(f"jsonld/product-{handle}.jsonld", json.dumps(product_jsonld(prod, p), ensure_ascii=False, indent=2))
    w("shopify/aiv-product-jsonld.liquid", SHOPIFY_PRODUCT_LIQUID)
    w("shopify/aiv-organization-jsonld.liquid",
      SHOPIFY_ORG_LIQUID.replace("__SAME_AS__", json.dumps(p.get("social") or ["__ADD_SOCIAL_URLS__"])))
    w("llms.txt", llms_txt(p))
    for fname, text in content_drafts(p, provider, meter).items():
        w(f"content/{fname}", text)
    w("cloudflare_allow_ai_crawlers.md", CLOUDFLARE_MD)
    readme = FIXPACK_README.format(name=p["name"] or p["domain"], root=res["root"])
    if res.get("visibility", {}).get("simulated"):
        readme = ("> ⚠️ SIMULATED / 模拟：本修复包生成时 AI 引擎为 stub，内容草稿是模板，AI 推荐数据是模拟的。仅供内部测试。\n"
                  "> Generated with the stub engine: content drafts are templates and AI data is simulated. Internal test only.\n\n") + readme
        (fp / "SIMULATED.txt").write_text("Generated with the simulated stub engine. Internal test only; not a public sample.\n")
        files["SIMULATED.txt"] = 1
    w("README.md", readme)
    zpath = Path(out_dir) / "fixpack.zip"
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(fp.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(fp.parent))
    return {"dir": str(fp), "zip": str(zpath), "files": files}


