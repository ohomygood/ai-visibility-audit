# ------------------------------------------------------------------ llms.txt
def llms_txt(p: dict) -> str:
    name = p["name"] or p["domain"]
    root = p["final_url"] or p["base_url"]
    lines = [f"# {name}", "", f"> {p.get('description') or '__ONE_SENTENCE_ABOUT_YOUR_STORE__'}", ""]
    facts = [f"- Website: {root}"]
    if p.get("product_types"):
        facts.append(f"- Main categories: {', '.join(p['product_types'][:6])}")
    if p.get("currency"):
        facts.append(f"- Prices shown in {p['currency']}")
    facts += ["- Ships to: __COUNTRIES__", "- Returns: __RETURN_POLICY_SUMMARY__", "- Support: __SUPPORT_EMAIL__"]
    lines += facts + ["", "## Products", ""]
    for pr in p.get("products", [])[:10]:
        t = pr.get("title") or pr.get("handle")
        desc = (pr.get("description") or "")[:140]
        price = f" — {pr['price']} {p.get('currency') or ''}".rstrip() if pr.get("price") else ""
        lines.append(f"- [{t}]({pr['url']}){price}{': ' + desc if desc else ''}")
    if p.get("collections"):
        lines += ["", "## Collections", ""]
        for c in p["collections"][:10]:
            lines.append(f"- [{c.rstrip('/').rsplit('/', 1)[-1].replace('-', ' ').title()}]({c})")
    lines += ["", "## Policies", ""]
    pol = p.get("policy_pages") or []
    if pol:
        for u in pol[:8]:
            lines.append(f"- [{urlparse(u).path.strip('/').rsplit('/', 1)[-1].replace('-', ' ').title()}]({u})")
    else:
        lines += [f"- [Shipping policy]({root}policies/shipping-policy)", f"- [Refund policy]({root}policies/refund-policy)"]
    lines += ["", "## Optional", "", f"- [Sitemap]({root}sitemap.xml)"]
    return "\n".join(lines) + "\n"


