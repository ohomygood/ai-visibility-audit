def content_drafts(p: dict, provider: Provider, meter: CostMeter) -> dict:
    brand = p["name"] or p["domain"]
    cat = (p.get("product_types") or ["products"])[0]
    facts = json.dumps({k: p.get(k) for k in ("name", "domain", "description", "product_types", "currency", "social")} |
                       {"products": [{k: x.get(k) for k in ("title", "url", "price", "description")} for x in p.get("products", [])[:6]]},
                       ensure_ascii=False)[:3500]
    out = {}
    for fname, title, spec in DRAFT_SPECS:
        if provider.simulated:
            out[fname] = _template_draft(fname, title, p)
            continue
        prompt = (f"Write {spec.format(brand=brand, cat=cat)}\nUse ONLY these facts about the store; for anything unknown "
                  f"write a placeholder like __SHIPPING_DAYS__ instead of inventing it. Output Markdown.\nFacts: {facts}")
        try:
            r = meter.run(provider, prompt, f"draft:{fname}", web_search=False, temperature=0.4, max_tokens=1400)
            out[fname] = r.text if r.text and not r.error else _template_draft(fname, title, p)
        except BudgetExceeded:
            out[fname] = _template_draft(fname, title, p)
    return out


