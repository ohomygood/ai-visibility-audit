# ------------------------------------------------------------------ robots
def robots_snippet(res: dict) -> str:
    blocked = [t for t, v in res["robots"].get("tokens", {}).items() if not v["allowed"]]
    lines = ["# --- AI crawler access (generated by AI Visibility Audit) ---",
             "# Answer-time crawlers (needed to be cited / recommended): OAI-SearchBot, ChatGPT-User,",
             "# PerplexityBot, Perplexity-User, Claude-SearchBot, Claude-User.",
             "# Training crawlers (GPTBot, ClaudeBot, Google-Extended, Applebot-Extended) are optional:",
             "# delete their lines if you do not want your content used for model training.",
             f"# Currently blocked on your site: {', '.join(blocked) if blocked else 'none'}", ""]
    for t in ALLOW_TOKENS:
        lines.append(f"User-agent: {t}")
    lines.append("Allow: /")
    lines += [f"Disallow: {p}" for p in PRIVATE_PATHS]
    lines.append("")
    if not res["robots"].get("sitemaps"):
        lines.append(f"Sitemap: {res['root']}sitemap.xml")
    return "\n".join(lines) + "\n"


def shopify_robots_liquid(res: dict) -> str:
    # Shopify: Online Store → Themes → Edit code → Add a new template → robots.txt
    body = robots_snippet(res).replace(f"Sitemap: {res['root']}sitemap.xml\n", "")
    return ("{%- comment -%} AI Visibility Audit: keeps Shopify's default rules and appends AI crawler groups {%- endcomment -%}\n"
            "{% for group in robots.default_groups %}\n"
            "  {{- group.user_agent }}\n"
            "  {%- for rule in group.rules -%}\n"
            "    {{ rule }}\n"
            "  {%- endfor -%}\n"
            "  {%- if group.sitemap != blank %}\n"
            "    {{ group.sitemap }}\n"
            "  {%- endif %}\n"
            "{% endfor %}\n\n" + body)


# ------------------------------------------------------------------ JSON-LD
def organization_jsonld(p: dict) -> dict:
    d = {"@context": "https://schema.org", "@type": "Organization", "name": p["name"] or p["domain"],
         "url": p["final_url"] or p["base_url"]}
    if p.get("logo"):
        d["logo"] = p["logo"]
    if p.get("description"):
        d["description"] = p["description"][:300]
    d["sameAs"] = p.get("social") or ["__ADD_YOUR_SOCIAL_PROFILE_URLS__"]
    d["contactPoint"] = {"@type": "ContactPoint", "contactType": "customer support",
                         "email": "__SUPPORT_EMAIL__", "availableLanguage": ["en", "zh"]}
    return d


def product_jsonld(prod: dict, p: dict) -> dict:
    cur = p.get("currency") or "__CURRENCY__"
    d = {"@context": "https://schema.org", "@type": "Product", "name": prod.get("title") or "__PRODUCT_NAME__",
         "url": prod["url"], "image": [prod["image"]] if prod.get("image") else ["__IMAGE_URL__"],
         "description": prod.get("description") or "__SHORT_DESCRIPTION__",
         "brand": {"@type": "Brand", "name": prod.get("vendor") or p["name"] or "__BRAND__"},
         "sku": prod.get("sku") or "__SKU__"}
    if prod.get("gtin") and re.fullmatch(r"\d{8,14}", prod["gtin"]):
        d["gtin"] = prod["gtin"]
    d["offers"] = {"@type": "Offer", "url": prod["url"], "price": prod.get("price") or "__PRICE__",
                   "priceCurrency": cur, "itemCondition": "https://schema.org/NewCondition",
                   "availability": "https://schema.org/InStock" if prod.get("available") is not False
                   else "https://schema.org/OutOfStock",
                   "seller": {"@type": "Organization", "name": p["name"] or p["domain"]},
                   "hasMerchantReturnPolicy": {"@type": "MerchantReturnPolicy",
                                               "applicableCountry": "__COUNTRY_CODE__",
                                               "returnPolicyCategory": "https://schema.org/MerchantReturnFiniteReturnWindow",
                                               "merchantReturnDays": "__RETURN_DAYS__"}}
    return d


